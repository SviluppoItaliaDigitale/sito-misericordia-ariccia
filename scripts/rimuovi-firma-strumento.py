#!/usr/bin/env python3
"""
Toglie da commenti, revisioni e descrizioni di PR e issue la riga di firma che
la piattaforma delle sessioni aggiunge da sola a ogni testo pubblicato su GitHub
(«Generated by [Claude Code](…)», il link alla sessione, eventuali trailer).

Perché esiste (06/10/2026). La regola della firma dei lavori (`.claude/rules/
firma-dei-lavori.md`, in ogni repository) vieta qualunque riferimento allo
strumento nei testi pubblicati. La riga però la aggiunge il canale delle
sessioni a ogni scrittura, comprese le modifiche: dalla sessione non si
toglie. Un workflow GitHub Actions scrive invece con il GITHUB_TOKEN, che non
passa da quel canale, e la riga resta tolta.

Tocca solo testi scritti dall'account proprietario del repository, e solo la
coda del testo: righe di firma finali e il separatore «---» che le precede.
Il resto del testo resta identico.

Pull request dei passaggi (dal 14/10/2026). Quando si chiude una pull request
su un ramo `chatgpt/…` (passaggio preparato con `passa-a.py nuovo`) o `codex/…`
(consegna aperta dal task), toglie quello che `passa-a.py chiudi` dovrebbe
togliere e che dalle sessioni cloud non può cancellare (il canale di GitHub
risponde 403): il commento di avvio «@codex …» dell'account, i commenti degli
account degli strumenti (i rapporti di github-actions[bot] restano) e il ramo.
Le revisioni inviate non si possono cancellare. Cancella anche i rami di
lavoro `claude/…` delle pull request unite, senza toccarne i commenti.
Un ramo resta se un'altra pull request aperta lo usa o se dopo la chiusura
ha ricevuto commit nuovi.

Uso:
  rimuovi-firma-strumento.py --evento              # dal workflow, sul testo dell'evento
  rimuovi-firma-strumento.py --passaggio           # dal workflow, sulla PR appena chiusa
  rimuovi-firma-strumento.py --tutti [--dal AAAA-MM-GG | --giorni N] [--max N]
                             [--giri N --pausa SECONDI] [--prova]

GitHub limita le scritture (circa 500 l'ora): un giro corregge al massimo
--max testi, e con --giri lo script aspetta --pausa secondi e ricomincia
finché non resta nulla.

Variabili: GITHUB_TOKEN, GITHUB_REPOSITORY (owner/repo), GITHUB_API_URL,
GITHUB_EVENT_NAME e GITHUB_EVENT_PATH (solo --evento). Solo libreria standard.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

API = os.environ.get("GITHUB_API_URL", "https://api.github.com").rstrip("/")


def _repo_da_git() -> str:
    """owner/repo dal remoto `origin`, per le esecuzioni a mano fuori da GitHub Actions."""
    try:
        url = subprocess.run(["git", "config", "--get", "remote.origin.url"],
                             capture_output=True, text=True, check=False).stdout.strip()
    except OSError:
        return ""
    m = re.search(r"github\.com[:/]([^/\s]+/[^/\s]+?)(?:\.git)?/?$", url)
    return m.group(1) if m else ""


# In GitHub Actions è sempre impostato GITHUB_REPOSITORY; a mano si legge dal
# remoto, così lo stesso file vale in ogni repository del kit.
REPO = os.environ.get("GITHUB_REPOSITORY") or _repo_da_git()
if not REPO:
    sys.exit("repository non riconosciuto: imposta GITHUB_REPOSITORY=owner/repo")
OWNER = REPO.split("/")[0]
TOKEN = os.environ.get("GITHUB_TOKEN", "")

# Righe che possono chiudere un testo e vanno tolte (solo in coda).
RIGHE_FIRMA = [
    re.compile(r"^_?Generated (?:by|with) \[Claude Code\]\([^)]*\)_?\.?$", re.I),
    re.compile(r"^🤖\s*Generated (?:by|with) \[Claude Code\]\([^)]*\)\.?$", re.I),
    re.compile(r"^<?https://claude\.ai/code/session_[A-Za-z0-9_-]+>?$"),
    re.compile(r"^Claude-Session:\s*\S+$", re.I),
    re.compile(r"^Co-Authored-By:\s*Claude\b.*$", re.I),
]
RIGA_SEPARATORE = re.compile(r"^(?:-{3,}|\*{3,}|_{3,})$")

# Pull request dei passaggi e account degli strumenti: gli stessi criteri di `passa-a.py`.
RAMO_PASSAGGIO = re.compile(r"^(?:chatgpt|codex)/")
# Rami di lavoro delle sessioni: dopo il merge non servono più e il loro nome resterebbe in vista.
RAMO_SESSIONE = re.compile(r"^claude/")
BOT_STRUMENTO = re.compile(r"codex|chatgpt|openai|claude|anthropic|gemini|jules|copilot", re.IGNORECASE)


def pulisci(testo: str) -> str:
    """Restituisce il testo senza le righe di firma in coda (idempotente)."""
    if not testo:
        return testo
    righe = testo.replace("\r\n", "\n").split("\n")
    tolto = False
    while righe:
        ultima = righe[-1].strip()
        if not ultima:
            righe.pop()
            continue
        if any(p.match(ultima) for p in RIGHE_FIRMA):
            righe.pop()
            tolto = True
            continue
        if tolto and RIGA_SEPARATORE.match(ultima):
            righe.pop()
            continue
        break
    if not tolto:
        return testo
    return "\n".join(righe).rstrip()


def chiama(metodo: str, url: str, dati: dict | None = None):
    corpo = json.dumps(dati).encode() if dati is not None else None
    req = urllib.request.Request(url, data=corpo, method=metodo)
    req.add_header("Accept", "application/vnd.github+json")
    req.add_header("X-GitHub-Api-Version", "2022-11-28")
    req.add_header("User-Agent", "rimuovi-firma-strumento")
    if TOKEN:
        req.add_header("Authorization", f"Bearer {TOKEN}")
    if corpo is not None:
        req.add_header("Content-Type", "application/json")
    for tentativo in range(4):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                testo = r.read().decode() or "null"
                return json.loads(testo)
        except urllib.error.HTTPError as e:
            # Limiti secondari di GitHub sulle scritture: si aspetta e si riprova.
            if e.code in (403, 429) and tentativo < 3:
                attesa = int(e.headers.get("Retry-After") or 60)
                print(f"  limite di GitHub ({e.code}), attendo {attesa} s", flush=True)
                time.sleep(attesa)
                continue
            raise


def elenco(url: str, massimo_pagine: int = 50) -> list[dict]:
    out: list[dict] = []
    sep = "&" if "?" in url else "?"
    for pagina in range(1, massimo_pagine + 1):
        dati = chiama("GET", f"{url}{sep}per_page=100&page={pagina}") or []
        out.extend(dati)
        if len(dati) < 100:
            break
    return out


def dell_account(oggetto: dict) -> bool:
    return (oggetto.get("user") or {}).get("login") == OWNER


def di_strumento(oggetto: dict) -> bool:
    """Vero per i testi di un account di strumento (un bot come chatgpt-codex-connector[bot]),
    falso per github-actions[bot], i cui rapporti sono del repository."""
    utente = oggetto.get("user") or {}
    login = utente.get("login") or ""
    return (utente.get("type") == "Bot" or "[bot]" in login) and bool(BOT_STRUMENTO.search(login))


class Contatore:
    def __init__(self, prova: bool, massimo: int):
        self.prova, self.massimo, self.fatti, self.trovati = prova, massimo, 0, 0
        self.eliminati, self.non_eliminati = 0, 0

    def elimina(self, url: str, etichetta: str) -> None:
        """Cancella un commento o un ramo; 404 e 422 vogliono dire che non c'è già più."""
        print(f"  {'[prova] ' if self.prova else ''}cancello {etichetta}", flush=True)
        if self.prova:
            self.eliminati += 1
            return
        try:
            chiama("DELETE", url)
            self.eliminati += 1
            time.sleep(1.0)   # restare sotto i limiti di GitHub sulle scritture
        except urllib.error.HTTPError as e:
            if e.code in (404, 422):
                print(f"    già tolto ({e.code})")
            else:
                self.non_eliminati += 1
                print(f"    non riuscito: HTTP {e.code}", flush=True)

    def esaurito(self) -> bool:
        return self.fatti >= self.massimo

    def correggi(self, metodo: str, url: str, campo_body: str, testo: str, etichetta: str) -> None:
        nuovo = pulisci(testo)
        if nuovo == testo:
            return
        self.trovati += 1
        if not nuovo.strip():
            print(f"  [salto] {etichetta}: senza la firma resterebbe vuoto")
            return
        if self.esaurito():
            return
        print(f"  {'[prova] ' if self.prova else ''}{etichetta}", flush=True)
        if not self.prova:
            chiama(metodo, url, {campo_body: nuovo})
            time.sleep(1.0)   # restare sotto i limiti di GitHub sulle scritture
        self.fatti += 1


def pulisci_passaggio(pr: dict, c: Contatore) -> None:
    """Pull request chiusa su un ramo chatgpt/* o codex/*: toglie il commento di avvio «@codex …»
    dell'account, i commenti degli strumenti e il ramo. Pull request unita da un ramo claude/*: solo
    il ramo. Il ramo resta se un'altra PR aperta lo usa o se ha commit arrivati dopo la chiusura."""
    n = pr["number"]
    testa = pr.get("head") or {}
    ramo = testa.get("ref") or ""
    passaggio = bool(RAMO_PASSAGGIO.match(ramo))
    sessione = bool(RAMO_SESSIONE.match(ramo)) and bool(pr.get("merged_at"))
    if pr.get("state") != "closed" or not (passaggio or sessione):
        return
    if ((testa.get("repo") or {}).get("full_name") or "").lower() != REPO.lower():
        print(f"  #{n}: il ramo {ramo} è in un altro repository, non lo tocco")
        return
    base = f"{API}/repos/{REPO}"
    if passaggio:
        for o in elenco(f"{base}/issues/{n}/comments", massimo_pagine=5):
            avvio = dell_account(o) and (o.get("body") or "").strip().lower().startswith("@codex")
            if avvio or di_strumento(o):
                c.elimina(f"{base}/issues/comments/{o['id']}", f"commento {o['id']} su #{n}")
        for o in elenco(f"{base}/pulls/{n}/comments", massimo_pagine=5):
            if di_strumento(o):
                c.elimina(f"{base}/pulls/comments/{o['id']}", f"commento di revisione {o['id']} su #{n}")
    ref = urllib.parse.quote(ramo, safe="/")
    try:
        attuale = chiama("GET", f"{base}/git/ref/heads/{ref}") or {}
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return   # ramo già cancellato
        raise
    if (attuale.get("object") or {}).get("sha") != testa.get("sha"):
        print(f"  ramo {ramo}: dopo la chiusura di #{n} ha ricevuto commit nuovi, resta")
        return
    testa_q = urllib.parse.quote(f"{OWNER}:{ramo}", safe="")
    if chiama("GET", f"{base}/pulls?state=open&head={testa_q}&per_page=5"):
        print(f"  ramo {ramo}: lo usa un'altra pull request aperta, resta")
        return
    c.elimina(f"{base}/git/refs/heads/{ref}", f"ramo {ramo} di #{n}")


def modo_passaggio() -> int:
    with open(os.environ["GITHUB_EVENT_PATH"], encoding="utf-8") as f:
        ev = json.load(f)
    pr = ev.get("pull_request") or {}
    if not pr:
        print("evento senza pull request")
        return 0
    c = Contatore(prova=False, massimo=0)
    pulisci_passaggio(pr, c)
    print(f"cancellati: {c.eliminati}" + (f" · non riusciti: {c.non_eliminati}" if c.non_eliminati else ""))
    return 1 if c.non_eliminati else 0


def modo_evento() -> int:
    nome = os.environ.get("GITHUB_EVENT_NAME", "")
    with open(os.environ["GITHUB_EVENT_PATH"], encoding="utf-8") as f:
        ev = json.load(f)
    c = Contatore(prova=False, massimo=10)
    base = f"{API}/repos/{REPO}"
    if nome == "issue_comment":
        o = ev["comment"]
        if dell_account(o):
            c.correggi("PATCH", f"{base}/issues/comments/{o['id']}", "body", o.get("body") or "", f"commento {o['id']}")
    elif nome == "pull_request_review_comment":
        o = ev["comment"]
        if dell_account(o):
            c.correggi("PATCH", f"{base}/pulls/comments/{o['id']}", "body", o.get("body") or "", f"commento di revisione {o['id']}")
    elif nome == "pull_request_review":
        o, n = ev["review"], ev["pull_request"]["number"]
        if dell_account(o):
            c.correggi("PUT", f"{base}/pulls/{n}/reviews/{o['id']}", "body", o.get("body") or "", f"revisione {o['id']} su #{n}")
    elif nome in ("pull_request", "pull_request_target"):
        o = ev["pull_request"]
        if dell_account(o):
            c.correggi("PATCH", f"{base}/pulls/{o['number']}", "body", o.get("body") or "", f"descrizione PR #{o['number']}")
    elif nome == "issues":
        o = ev["issue"]
        if dell_account(o):
            c.correggi("PATCH", f"{base}/issues/{o['number']}", "body", o.get("body") or "", f"descrizione issue #{o['number']}")
    else:
        print(f"evento {nome!r} non gestito")
    print(f"testi corretti: {c.fatti}")
    return 0


def modo_tutti(dal: str, massimo: int, prova: bool) -> tuple[int, int]:
    """Un giro: restituisce (testi con la firma rimasti, cancellazioni non riuscite)."""
    base = f"{API}/repos/{REPO}"
    since = f"{dal}T00:00:00Z"
    c = Contatore(prova=prova, massimo=massimo)

    print("Commenti su issue e PR")
    for o in elenco(f"{base}/issues/comments?since={since}"):
        if dell_account(o):
            c.correggi("PATCH", f"{base}/issues/comments/{o['id']}", "body", o.get("body") or "", f"commento {o['id']}")

    print("Commenti nelle revisioni")
    for o in elenco(f"{base}/pulls/comments?since={since}"):
        if dell_account(o):
            c.correggi("PATCH", f"{base}/pulls/comments/{o['id']}", "body", o.get("body") or "", f"commento di revisione {o['id']}")

    print("Descrizioni di PR e issue, e revisioni")
    interrotto = False
    for o in elenco(f"{base}/issues?state=all&since={since}"):
        n = o["number"]
        if "pull_request" in o:
            if dell_account(o):
                c.correggi("PATCH", f"{base}/pulls/{n}", "body", o.get("body") or "", f"descrizione PR #{n}")
            if c.esaurito() and not prova:
                # Giro pieno: inutile leggere le revisioni delle PR restanti.
                # Il resto non è contato, quindi si segnala che il lavoro non
                # è finito e il giro successivo riprende.
                interrotto = True
                break
            for r in elenco(f"{base}/pulls/{n}/reviews", massimo_pagine=3):
                if dell_account(r):
                    c.correggi("PUT", f"{base}/pulls/{n}/reviews/{r['id']}", "body", r.get("body") or "", f"revisione {r['id']} su #{n}")
        elif dell_account(o):
            c.correggi("PATCH", f"{base}/issues/{n}", "body", o.get("body") or "", f"descrizione issue #{n}")

    print("Pull request chiuse: passaggi (rami chatgpt/* e codex/*) e rami di lavoro claude/* uniti")
    for pagina in range(1, 51):
        lotto = chiama("GET", f"{base}/pulls?state=closed&sort=updated&direction=desc"
                              f"&per_page=100&page={pagina}") or []
        for pr in lotto:
            if (pr.get("updated_at") or "") < since:
                lotto = []
                break
            pulisci_passaggio(pr, c)
        if len(lotto) < 100:
            break
    if c.eliminati or c.non_eliminati:
        print(f"cancellazioni: {c.eliminati}" + (" (prova)" if prova else "")
              + (f" · non riuscite: {c.non_eliminati}" if c.non_eliminati else ""))

    resto = c.trovati - c.fatti
    if interrotto:
        # Il giro si è fermato prima di vedere tutto: quanto resta non si sa,
        # ma non è zero finché un giro non arriva in fondo.
        resto = max(resto, 1)
    print(f"\ntesti con la firma: {c.trovati} · {'da correggere (prova)' if prova else 'corretti'}: {c.fatti}"
          + (" · giro interrotto al limite, il prossimo riprende" if interrotto
             else f" · rimasti per il prossimo giro: {resto}" if resto > 0 else ""))
    return resto, c.non_eliminati


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--evento", action="store_true", help="corregge il testo dell'evento GitHub in corso")
    g.add_argument("--passaggio", action="store_true",
                   help="pulisce la pull request di un passaggio appena chiusa (evento GitHub in corso)")
    g.add_argument("--tutti", action="store_true", help="passa tutti i testi dal giorno indicato")
    ap.add_argument("--dal", default="", help="data di inizio AAAA-MM-GG (con --tutti)")
    ap.add_argument("--giorni", type=int, default=3, help="in alternativa a --dal: ultimi N giorni")
    ap.add_argument("--max", type=int, default=400, help="massimo di correzioni per giro (limiti di GitHub)")
    ap.add_argument("--giri", type=int, default=1, help="giri al massimo, finché resta qualcosa")
    ap.add_argument("--pausa", type=int, default=3700, help="secondi di attesa fra un giro e l'altro")
    ap.add_argument("--prova", action="store_true", help="elenca senza modificare")
    a = ap.parse_args()
    if not TOKEN and not a.prova:
        print("GITHUB_TOKEN mancante", file=sys.stderr)
        return 2
    if a.evento:
        return modo_evento()
    if a.passaggio:
        return modo_passaggio()
    dal = a.dal or time.strftime("%Y-%m-%d", time.gmtime(time.time() - a.giorni * 86400))
    falliti = 0
    for giro in range(1, a.giri + 1):
        print(f"=== giro {giro} di {a.giri}, testi dal {dal} ===", flush=True)
        resto, falliti = modo_tutti(dal, a.max, a.prova)
        if (resto <= 0 and not falliti) or a.prova or giro == a.giri:
            break
        print(f"attendo {a.pausa} s per i limiti di GitHub sulle scritture", flush=True)
        time.sleep(a.pausa)
    if falliti:
        # Cancellazioni non riuscite anche all'ultimo giro: il passo fallisce, così il run è rosso e si vede.
        print(f"cancellazioni non riuscite: {falliti}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
